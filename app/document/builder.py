"""Word (.docx) builder engine with executive styling, custom typography, callouts, and tables."""
import os
import uuid
import logging
from datetime import datetime
from pathlib import Path
from typing import List, Optional

import docx
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn

from app.models.schemas import DocumentSection, TableData, DocumentMetadata
from app.config import settings

logger = logging.getLogger("DocAgent.DocxBuilder")

# Professional Corporate Palette
COLOR_PRIMARY_HEX = "1B365D"       # Deep Navy
COLOR_ACCENT_HEX = "2A6F97"        # Slate Blue
COLOR_DARK_TEXT_HEX = "1E293B"     # Charcoal Slate
COLOR_LIGHT_BG_HEX = "F1F5F9"      # Soft Gray / Slate tint
COLOR_ZEBRA_HEX = "F8FAFC"         # Alternating table tint
COLOR_BORDER_HEX = "CBD5E1"        # Subtle border gray

COLOR_PRIMARY_RGB = RGBColor(27, 54, 93)
COLOR_ACCENT_RGB = RGBColor(42, 111, 151)
COLOR_DARK_TEXT_RGB = RGBColor(30, 41, 59)

class DocxBuilder:
    """Builds executive-ready Microsoft Word (.docx) documents."""

    def __init__(self):
        self.doc = Document()
        self._configure_page_margins()
        self._configure_default_styles()

    def _configure_page_margins(self):
        """Sets standard 1-inch margins."""
        sections = self.doc.sections
        for section in sections:
            section.top_margin = Inches(1.0)
            section.bottom_margin = Inches(1.0)
            section.left_margin = Inches(1.0)
            section.right_margin = Inches(1.0)
            
            # Configure Header & Footer
            header = section.header
            header_p = header.paragraphs[0]
            header_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            hrun = header_p.add_run("CONFIDENTIAL & PROPRIETARY | EXECUTIVE BRIEFING")
            hrun.font.size = Pt(8.5)
            hrun.font.color.rgb = RGBColor(148, 163, 184)

            footer = section.footer
            footer_p = footer.paragraphs[0]
            footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            frun = footer_p.add_run("Generated by DocAgent Autonomous AI Platform • Final Production Specification")
            frun.font.size = Pt(8.5)
            frun.font.color.rgb = RGBColor(148, 163, 184)

    def _configure_default_styles(self):
        """Configures typography for normal paragraphs and headings."""
        normal_style = self.doc.styles['Normal']
        normal_style.font.name = 'Calibri'
        normal_style.font.size = Pt(11)
        normal_style.font.color.rgb = COLOR_DARK_TEXT_RGB
        normal_style.paragraph_format.line_spacing = 1.15
        normal_style.paragraph_format.space_after = Pt(6)

    def add_title_block(self, title: str, doc_type: str, audience: str, assumptions: List[str]):
        """Adds a prominent executive title header with metadata table."""
        # Top banner category
        cat_p = self.doc.add_paragraph()
        cat_p.paragraph_format.space_before = Pt(0)
        cat_p.paragraph_format.space_after = Pt(2)
        c_run = cat_p.add_run(doc_type.upper())
        c_run.font.bold = True
        c_run.font.size = Pt(9.5)
        c_run.font.color.rgb = COLOR_ACCENT_RGB

        # Main Title
        title_p = self.doc.add_paragraph()
        title_p.paragraph_format.space_before = Pt(2)
        title_p.paragraph_format.space_after = Pt(8)
        t_run = title_p.add_run(title)
        t_run.font.bold = True
        t_run.font.size = Pt(22)
        t_run.font.color.rgb = COLOR_PRIMARY_RGB

        # Horizontal separator line
        self._add_colored_divider()

        # Metadata table
        meta_table = self.doc.add_table(rows=2, cols=3)
        meta_table.alignment = WD_TABLE_ALIGNMENT.CENTER
        meta_table.autofit = False

        col_widths = [Inches(2.1), Inches(2.1), Inches(2.3)]
        row0_data = [
            ("Date Generated", datetime.now().strftime("%B %d, %Y")),
            ("Document Status", "Approved / Production Draft"),
            ("Prepared By", "DocAgent Autonomous Engine")
        ]
        row1_data = [
            ("Target Audience", audience[:30]),
            ("Review Cycle", "Immediate Executive Steering"),
            ("Security Classification", "Enterprise Confidential")
        ]

        for row_idx, data in enumerate([row0_data, row1_data]):
            row = meta_table.rows[row_idx]
            for col_idx, (label, val) in enumerate(data):
                cell = row.cells[col_idx]
                cell.width = col_widths[col_idx]
                self._set_cell_background(cell, COLOR_LIGHT_BG_HEX)
                self._set_cell_margins(cell, top=80, bottom=80, left=100, right=100)
                
                p = cell.paragraphs[0]
                p.paragraph_format.space_after = Pt(2)
                lbl_run = p.add_run(f"{label}\n")
                lbl_run.font.size = Pt(8.5)
                lbl_run.font.bold = True
                lbl_run.font.color.rgb = COLOR_ACCENT_RGB
                
                val_run = p.add_run(val)
                val_run.font.size = Pt(9.5)
                val_run.font.color.rgb = COLOR_DARK_TEXT_RGB

        self.doc.add_paragraph().paragraph_format.space_after = Pt(8)

        # Assumptions callout block if present
        if assumptions:
            self.add_callout_box(
                "DOCUMENT ASSUMPTIONS & CONFLICT RESOLUTION:\n" +
                "\n".join([f"• {a}" for a in assumptions]),
                title="AUTONOMOUS ASSUMPTIONS REGISTER"
            )

    def _add_colored_divider(self):
        """Inserts a thin colored divider line."""
        p = self.doc.add_paragraph()
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(10)
        pBdr = parse_xml(f'<w:pBdr {nsdecls("w")}><w:bottom w:val="single" w:sz="18" w:space="1" w:color="{COLOR_PRIMARY_HEX}"/></w:pBdr>')
        p._p.get_or_add_pPr().append(pBdr)

    def add_callout_box(self, text: str, title: Optional[str] = None):
        """Adds a shaded callout box with a prominent left accent border."""
        table = self.doc.add_table(rows=1, cols=1)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = False
        
        cell = table.rows[0].cells[0]
        cell.width = Inches(6.5)
        self._set_cell_background(cell, COLOR_LIGHT_BG_HEX)
        self._set_cell_margins(cell, top=140, bottom=140, left=180, right=140)
        
        # Left accent border
        tcPr = cell._tc.get_or_add_tcPr()
        tcBorders = parse_xml(
            f'<w:tcBorders {nsdecls("w")}>'
            f'<w:top w:val="none"/>'
            f'<w:left w:val="single" w:sz="28" w:color="{COLOR_ACCENT_HEX}"/>'
            f'<w:bottom w:val="none"/>'
            f'<w:right w:val="none"/>'
            f'</w:tcBorders>'
        )
        tcPr.append(tcBorders)

        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(2)
        if title:
            t_run = p.add_run(f"{title}\n")
            t_run.font.bold = True
            t_run.font.size = Pt(9.5)
            t_run.font.color.rgb = COLOR_PRIMARY_RGB
            
        c_run = p.add_run(text)
        c_run.font.italic = True
        c_run.font.size = Pt(10)
        c_run.font.color.rgb = COLOR_DARK_TEXT_RGB

        self.doc.add_paragraph().paragraph_format.space_after = Pt(4)

    def add_section(self, section: DocumentSection):
        """Renders a section with formatted heading, text, callouts, and tables."""
        # Heading
        head_p = self.doc.add_paragraph()
        if section.level == 1:
            head_p.paragraph_format.space_before = Pt(14)
            head_p.paragraph_format.space_after = Pt(4)
            h_run = head_p.add_run(section.title)
            h_run.font.bold = True
            h_run.font.size = Pt(15)
            h_run.font.color.rgb = COLOR_PRIMARY_RGB
        else:
            head_p.paragraph_format.space_before = Pt(10)
            head_p.paragraph_format.space_after = Pt(3)
            h_run = head_p.add_run(section.title)
            h_run.font.bold = True
            h_run.font.size = Pt(12.5)
            h_run.font.color.rgb = COLOR_ACCENT_RGB

        # Content narrative
        body_p = self.doc.add_paragraph()
        body_p.paragraph_format.space_after = Pt(6)
        b_run = body_p.add_run(section.content)
        b_run.font.size = Pt(10.5)

        # Callout block if present
        if section.callout:
            self.add_callout_box(section.callout)

        # Bullet points if present
        if section.bullet_points:
            for bp in section.bullet_points:
                bp_p = self.doc.add_paragraph(style='List Bullet')
                bp_p.paragraph_format.space_after = Pt(3)
                bp_run = bp_p.add_run(bp)
                bp_run.font.size = Pt(10.5)

        # Table if present
        if section.table:
            self.add_table(section.table)

    def add_table(self, table_data: TableData):
        """Renders an executive styled table with header shading and alternating rows."""
        if table_data.caption:
            cap_p = self.doc.add_paragraph()
            cap_p.paragraph_format.space_before = Pt(6)
            cap_p.paragraph_format.space_after = Pt(3)
            c_run = cap_p.add_run(table_data.caption)
            c_run.font.bold = True
            c_run.font.size = Pt(9.5)
            c_run.font.color.rgb = COLOR_PRIMARY_RGB

        num_cols = len(table_data.headers)
        num_rows = len(table_data.rows) + 1
        table = self.doc.add_table(rows=num_rows, cols=num_cols)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = True

        # Header Row
        header_row = table.rows[0]
        self._set_repeat_header(header_row)
        for idx, h_text in enumerate(table_data.headers):
            cell = header_row.cells[idx]
            self._set_cell_background(cell, COLOR_PRIMARY_HEX)
            self._set_cell_margins(cell, top=100, bottom=100, left=100, right=100)
            self._set_cell_borders(cell)
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(h_text)
            run.font.bold = True
            run.font.size = Pt(9.5)
            run.font.color.rgb = RGBColor(255, 255, 255)

        # Data Rows
        for r_idx, row_values in enumerate(table_data.rows):
            row = table.rows[r_idx + 1]
            bg_color = COLOR_ZEBRA_HEX if r_idx % 2 == 1 else "FFFFFF"
            for c_idx, val in enumerate(row_values):
                if c_idx < num_cols:
                    cell = row.cells[c_idx]
                    self._set_cell_background(cell, bg_color)
                    self._set_cell_margins(cell, top=80, bottom=80, left=100, right=100)
                    self._set_cell_borders(cell)
                    p = cell.paragraphs[0]
                    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                    run = p.add_run(str(val))
                    run.font.size = Pt(9.5)
                    run.font.color.rgb = COLOR_DARK_TEXT_RGB

        self.doc.add_paragraph().paragraph_format.space_after = Pt(8)

    def _set_cell_background(self, cell, hex_color: str):
        """Sets the background XML shading of a cell."""
        shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hex_color}"/>')
        cell._tc.get_or_add_tcPr().append(shading)

    def _set_cell_margins(self, cell, top=80, bottom=80, left=100, right=100):
        """Sets internal cell padding in twentieths of a point (dxa)."""
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = parse_xml(
            f'<w:tcMar {nsdecls("w")}>'
            f'<w:top w:w="{top}" w:type="dxa"/>'
            f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
            f'<w:left w:w="{left}" w:type="dxa"/>'
            f'<w:right w:w="{right}" w:type="dxa"/>'
            f'</w:tcMar>'
        )
        tcPr.append(tcMar)

    def _set_cell_borders(self, cell):
        """Applies subtle borders to cell edges."""
        tcPr = cell._tc.get_or_add_tcPr()
        borders = parse_xml(
            f'<w:tcBorders {nsdecls("w")}>'
            f'<w:top w:val="single" w:sz="4" w:space="0" w:color="{COLOR_BORDER_HEX}"/>'
            f'<w:bottom w:val="single" w:sz="4" w:space="0" w:color="{COLOR_BORDER_HEX}"/>'
            f'<w:left w:val="single" w:sz="4" w:space="0" w:color="{COLOR_BORDER_HEX}"/>'
            f'<w:right w:val="single" w:sz="4" w:space="0" w:color="{COLOR_BORDER_HEX}"/>'
            f'</w:tcBorders>'
        )
        tcPr.append(borders)

    def _set_repeat_header(self, row):
        """Ensures table header repeats across page boundaries."""
        trPr = row._tr.get_or_add_trPr()
        tblHeader = parse_xml(f'<w:tblHeader {nsdecls("w")}/>')
        trPr.append(tblHeader)

    def save(self, filename: Optional[str] = None) -> DocumentMetadata:
        """Saves the document and returns metadata."""
        doc_id = str(uuid.uuid4())[:8]
        if not filename:
            filename = f"Document_{doc_id}.docx"
        elif not filename.endswith(".docx"):
            filename = f"{filename}_{doc_id}.docx"
            
        file_path = settings.docs_dir / filename
        self.doc.save(str(file_path))
        
        file_size = os.path.getsize(file_path)
        logger.info(f"Generated DOCX saved: {file_path} ({file_size} bytes)")
        
        # Count sections and tables
        num_sections = len(self.doc.paragraphs)
        num_tables = len(self.doc.tables)

        return DocumentMetadata(
            doc_id=doc_id,
            filename=filename,
            file_path=str(file_path),
            file_size_bytes=file_size,
            download_url=f"/download/{doc_id}",
            total_sections=num_sections,
            total_tables=num_tables
        )
